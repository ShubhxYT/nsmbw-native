#!/usr/bin/env bash
# Emit the translated sources and data from the caller's local disc.
set -euo pipefail
cd "$1"
disc=$2
recipe=$3
jobs=$4

# Use the existing checksum handling without applying the desktop-only patches.
python3 - "$recipe" "$PWD" "$disc" <<'PY'
import runpy
import sys
from pathlib import Path
root, source, disc = map(Path, sys.argv[1:])
patches = runpy.run_path(str(root / "apply-patches.py"))
report = []
patches["patch_variant_hash"](source, disc, report)
print("\n".join(report))
PY

python3 projects/nsmbw/tools/unpack_game.py "$disc"
python3 projects/nsmbw/tools/prelink_rels.py
mkdir -p generated/functions build/base generated/build_shards
dotnet build translator/Translator.sln -c Release -v quiet -nologo
translator=(dotnet translator/src/Translator.Cli/bin/Release/net8.0/Translator.Cli.dll)
project=(--project projects/nsmbw/recomp.yml)
"${translator[@]}" translate-recursive 0x80004050 "${project[@]}" --outdir generated/functions \
    --output-metadata generated/base_translation_output.json --production-source-bundle generated/base_translation_sources.bin \
    --no-function-files --prune-stale --threads "$jobs"
"${translator[@]}" emit-base-manifest "${project[@]}" --out build/base --functions-dir generated/functions \
    --translation-output-metadata generated/base_translation_output.json --region E
"${translator[@]}" generate-data-init "${project[@]}"
"${translator[@]}" emit-build-shards "${project[@]}" --base-metadata generated/base_translation_output.json \
    --base-functions-dir generated/functions --native-source-dir runtime/src --out generated/build_shards

# The assembly generated by the host translator includes absolute paths to the data blobs.
python3 - <<'PY'
from pathlib import Path
asm = Path("generated/data_sections_init_blobs.S")
text = asm.read_text()
for blob in Path("generated/data_sections_init_blobs").glob("*.bin"):
    text = text.replace(f'\x22{blob.resolve()}\x22', f'\x22/src/{blob.as_posix()}\x22')
asm.write_text(text)
PY
